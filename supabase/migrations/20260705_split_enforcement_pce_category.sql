-- Категория "Исполнение решения суда / ЧСИ" разделена на две:
-- "Исполнение решения суда" (юристы/адвокаты) и "ЧСИ" (частный судебный
-- исполнитель — свой отдельный специалист, category.pce в переводах).
-- Существующих заявок с этой категорией на момент разделения не было
-- (проверено), поэтому строка в commission_rates просто переименована,
-- а не мигрирована построчно.
UPDATE commission_rates SET category = 'Исполнение решения суда'
  WHERE category = 'Исполнение решения суда / ЧСИ';

INSERT INTO commission_rates (category, percent) VALUES ('ЧСИ', 10.00)
ON CONFLICT (category) DO NOTHING;
